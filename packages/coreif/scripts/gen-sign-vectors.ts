// Regenerates test/sign-vectors.json, the signing test vectors shared with the LTE firmware
// (copy the file to the firmware's QEMU test). Run: npx tsx packages/coreif/scripts/gen-sign-vectors.ts
// Changing the output means the wire format changed: the firmware must change with it.
import { createHash, createHmac } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { buildCommandFrames } from '../src/commands';
import { bootHex, cabinetKey, identSig, keyFingerprint, signCommand, verifyCommand } from '../src/sign';

const master = Buffer.from([...Array(32).keys()]); // 00 01 .. 1f
const uid = '3a00470013504d3437323920';
const key = cabinetKey(master, uid);
const now = Date.UTC(2026, 9, 29, 11, 0, 0); // 2026-10-29T18:00:00+07:00
const boot = 42;

const commands = [
  { name: 'PMAN on', unsigned: buildCommandFrames('CTY0005', 'MANUAL_ALL', { on: true })[0]!, m: 1 },
  {
    name: 'longest: SET_SCHEDULE mode 2',
    unsigned: buildCommandFrames('CTY0005', 'SET_SCHEDULE', {
      mode: 2, on1: '18:00', off1: '05:30', on2: '18:15', off2: '05:45', branch1Enabled: true, branch2Enabled: true,
    })[0]!,
    m: 4294967295,
  },
  { name: 'PULSE_ON step 2', unsigned: buildCommandFrames('CTY0005', 'PULSE_ON', {})[1]!, m: 17 },
].map((c) => ({ ...c, boot, nowMs: now, signed: signCommand(c.unsigned, key, { boot, m: c.m }, now) }));

const ok = commands[0]!.signed;
const dev = { boot, lastM: 0, nowMs: now };
const rejects = [
  { name: 'value changed after signing', frame: ok.replace("PMAN'1", "PMAN'0"), dev },
  { name: 'signature upper case', frame: ok.replace(/CSIG'([0-9a-f]+)/, (_, s: string) => `CSIG'${s.toUpperCase()}`), dev },
  { name: 'no CSIG', frame: ok.slice(0, ok.lastIndexOf("&CSIG'")) + '$', dev },
  { name: 'unsigned frame', frame: commands[0]!.unsigned, dev },
  { name: 'other boot (device rebooted)', frame: ok, dev: { ...dev, boot: boot + 1 } },
  { name: 'replay: m not above the last accepted', frame: ok, dev: { ...dev, lastM: 1 } },
  { name: 'expired (91 s later)', frame: ok, dev: { ...dev, nowMs: now + 91_000 } },
  { name: 'signed for another cabinet key', frame: signCommand(commands[0]!.unsigned, cabinetKey(master, '000000000000000000000001'), { boot, m: 1 }, now), dev },
].map((r) => {
  const v = verifyCommand(r.frame, key, r.dev);
  if (v.ok) throw new Error(`reject case accepted: ${r.name}`);
  return { ...r, expect: v.reason };
});

const out = {
  note: 'Generated by packages/coreif/scripts/gen-sign-vectors.ts (Server repo). Same file in the firmware QEMU test. Hex is lower case.',
  primitives: {
    sha256_abc: createHash('sha256').update('abc').digest('hex'),
    // RFC 4231 test case 2
    hmac_rfc4231_2: { key: 'Jefe', data: 'what do ya want for nothing?', mac: createHmac('sha256', 'Jefe').update('what do ya want for nothing?').digest('hex') },
  },
  master: master.toString('hex'),
  uid,
  cabinetKey: key.toString('hex'),
  fingerprint: keyFingerprint(key),
  ident: [
    { ltid: 'CTY0005', boot, seq: bootHex(boot), sig: identSig(key, 'CTY0005', uid, bootHex(boot)) },
    // LTID is upper-cased before signing
    { ltid: 'cty0005', boot, seq: bootHex(boot), sig: identSig(key, 'cty0005', uid, bootHex(boot)) },
    { ltid: 'CTY0005', boot: 0xfffffffe, seq: bootHex(0xfffffffe), sig: identSig(key, 'CTY0005', uid, bootHex(0xfffffffe)) },
  ],
  commands,
  rejects,
};

writeFileSync(new URL('../test/sign-vectors.json', import.meta.url), `${JSON.stringify(out, null, 2)}\n`);
console.log(`sign-vectors.json: ${commands.length} commands, ${rejects.length} rejects`);
